use std::{fs, path::Path};

use crate::build::{collect_asset_stems, include_assets_path, to_const_name};

/// assets/sounds 内の効果音の一覧を生成
/// * `sounds_dir` - 効果音ディレクトリのパス
/// * `out_dir` - 出力ディレクトリのパス
pub(crate) fn generate_sounds_generated(sounds_dir: &Path, out_dir: &String) {
    let sound_names = collect_asset_stems(sounds_dir, "mp3");
    let mut output = String::from("// @generated by build.rs — do not edit\n\n");

    for sound_name in &sound_names {
        let const_name = to_const_name(sound_name);
        let asset_path = format!("assets/sounds/{sound_name}.mp3");
        output.push_str(&format!("#[allow(dead_code)]\n
pub const {const_name}: SoundSource = SoundSource::new(include_bytes!({}));\n",
            include_assets_path(&asset_path),
        ));
    }

    println!("cargo:warning=generated sounds: {:?}", sound_names);

    let out_path = Path::new(out_dir).join("sounds_generated.rs");
    fs::write(&out_path, output).expect("failed to write generated sounds");
}
